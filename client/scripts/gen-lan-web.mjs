// Generates src/lan/web/assets.generated.ts from assets/web: path -> { mime, base64 }.
// Run `npm run gen:lan-web` after changing anything under assets/web.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const webDir = join(root, 'assets', 'web');
const outFile = join(root, 'src', 'lan', 'web', 'assets.generated.ts');

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json',
  '.ico': 'image/x-icon',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
};

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => (entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]))
    .sort();
}

const lines = walk(webDir).map((file) => {
  const path = relative(webDir, file).split(sep).join('/');
  const mime = MIME[extname(file).toLowerCase()] ?? 'application/octet-stream';
  const base64 = readFileSync(file).toString('base64');
  return `  ${JSON.stringify(path)}: { mime: ${JSON.stringify(mime)}, base64: ${JSON.stringify(base64)} },`;
});

const source = `// Generated by scripts/gen-lan-web.mjs from assets/web; do not edit.
export interface WebAsset {
  mime: string;
  base64: string;
}

export const webAssets: Record<string, WebAsset> = {
${lines.join('\n')}
};
`;

writeFileSync(outFile, source);
console.log(`Wrote ${lines.length} assets to ${relative(root, outFile)}`);
